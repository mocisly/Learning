"""Generate and engrave excerpts using a piece-specific extraction profile."""
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import re
import subprocess
from .project import duration, write_text

def excerpt_length(profile, last):
    return (duration(profile['pickup_duration'], zero=True)
            + (last - profile['first_full_bar'] + 1) * duration(profile['bar_duration']))

def generate(piece):
    if not piece.segments:
        return []
    profile = piece.data['extraction']
    voices = profile['voices']
    source = piece.source.read_text(encoding='utf-8')
    marker = re.search(r'(?m)^\\score\s*\{', source)
    if not marker:
        raise ValueError(f'{piece.id}: cannot find a top-level score block')
    source = source[:marker.start()]
    source = re.sub(r'\\(?:autoLineBreaksOff|autoPageBreaksOff|pageBreak|break)\b', '', source)
    primary = re.escape(voices['primary'])
    opening = re.search(rf'(?m)^{primary}\s*=\s*(?:\\(?:relative|fixed)\s+[^{{\n]+)?\{{', source)
    if not opening:
        raise ValueError(f'{piece.id}: cannot find the opening of voice {voices["primary"]}')
    following = re.search(r'(?m)^[A-Za-z][A-Za-z_-]*\s*=', source[opening.end():])
    end = opening.end() + following.start() if following else len(source)
    start = opening.start()
    jobs = []
    for segment in piece.segments:
        first, last = segment['first_bar'], segment['last_bar']
        melody = source[start:end]
        if first > 1:
            offset = opening.end() - start
            melody = melody[:offset] + '\n  \\set Score.skipTypesetting = ##t' + melody[offset:]
        for bar, enabled in ((first - 1, True), (last, False)):
            if bar == 0 or (last == profile['last_bar'] and not enabled):
                continue
            command = '\\set Score.skipTypesetting = ##' + ('f' if enabled else 't')
            if enabled:
                key = segment['key']
                # Hidden earlier key changes must be reannounced on both staves.
                for staff in profile.get('staves', {'upper': 'up', 'lower': 'down'}).values():
                    command += f'\n  \\context Staff = "{staff}" {{ \\key {key["pitch"]} \\{key["mode"]} }}'
            melody, count = re.subn(rf'(% {bar}\s*\n)', lambda m: m[1] + '  ' + command + '\n', melody, count=1)
            if count != 1:
                raise ValueError(f'{piece.id}/{segment["id"]}: missing boundary comment % {bar}')
        length = excerpt_length(profile, last)
        engraving = piece.data.get('engraving', {})
        width = engraving.get('line_width_mm', 164)
        body = '% Generated by build.py; edit the piece source/configuration instead.\n'
        body += source[:start] + melody + source[end:]
        body += rf'''
\include "note-names.ily"
showFirstLength = s1*{length.numerator}/{length.denominator}
#(set-global-staff-size {engraving.get('staff_size', 18)})
\header {{ title = "" subtitle = "" composer = "" tagline = ##f }}
\paper {{
  paper-width = {width + 10}\mm
  left-margin = 5\mm
  right-margin = 5\mm
  line-width = {width}\mm
  indent = 0\mm
  short-indent = 0\mm
  print-page-number = ##f
  ragged-right = ##f
  ragged-last = ##f
}}
excerpt = \context Score <<
  \removeWithTag #'midiOnly \{profile.get('score_variable', 'pianoMusic')}
  \new NoteNames \with {{
    noteNameFunction = #letter-note-name
    \override NoteName.font-size = #-2
  }} <<
    \replaceWithTag #'silent {{ s8 }} \namesOnly \{voices['primary']}
    \namesOnly \{voices['upper_support']}
  >>
  \new NoteNames \with {{
    noteNameFunction = #letter-note-name
    \override NoteName.font-size = #-2
  }} << \namesOnly \{voices['accompaniment']} \namesOnly \{voices['lower_support']} >>
>>
\score {{
  \excerpt
  \layout {{
    \context {{ \Score skipTypesetting = ##{'f' if first == 1 else 't'} }}
  }}
}}
'''
        target = piece.output / f'part-{segment["id"]}.ly'
        write_text(target, body)
        jobs.append((piece, target))
    return jobs

def signature(piece, source):
    helper = piece.root / 'lilypond/note-names.ily'
    return hashlib.sha256(source.read_bytes() + helper.read_bytes() + b'crop-v1').hexdigest()

def engrave(job, *, force=False):
    piece, source = job
    output, stamp = source.with_suffix('.cropped.pdf'), source.with_suffix('.stamp.json')
    digest = signature(piece, source)
    if not force and output.exists() and stamp.exists():
        if json.loads(stamp.read_text(encoding='utf-8')).get('signature') == digest:
            return
    with source.with_suffix('.log').open('w', encoding='utf-8') as log:
        result = subprocess.run(['lilypond', '-dcrop', '-dno-print-pages', '-dno-point-and-click',
                        '-I', str(piece.root / 'lilypond'), '-o', str(source.with_suffix('')), str(source)],
                       cwd=piece.root, stdout=log, stderr=subprocess.STDOUT)
    if result.returncode:
        raise RuntimeError(f'LilyPond failed; see {source.with_suffix(".log")}')
    if not output.is_file() or not output.stat().st_size:
        raise RuntimeError(f'No practice PDF generated: {output}')
    write_text(stamp, json.dumps({'signature': digest}) + '\n')
    print(f'Built {piece.id}/{source.stem}', flush=True)

def build_practice(pieces, *, workers=3, force=False):
    jobs = [job for piece in pieces for job in generate(piece)]
    with ThreadPoolExecutor(max_workers=workers) as pool:
        list(pool.map(lambda job: engrave(job, force=force), jobs))
